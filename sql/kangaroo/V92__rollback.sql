-- Stop the application and back up first. Never discard saved notices or order evidence.
drop procedure if exists kg_rollback_stay_booking_notice;
delimiter $$
create procedure kg_rollback_stay_booking_notice()
begin
    if coalesce(@kg_allow_stay_booking_notice_rollback,0) <> 1 then
        signal sqlstate '45000' set message_text='V92 rollback requires stopped application and explicit authorization';
    end if;
    if exists (select 1 from kg_schema_version where version>92) then
        signal sqlstate '45000' set message_text='V92 rollback blocked by later migrations';
    end if;
    if exists (select 1 from kg_stay_order where char_length(agreement_version)>16) then
        signal sqlstate '45000' set message_text='V92 rollback blocked: new notice versions exist in orders';
    end if;
    if exists (select 1 from information_schema.columns where table_schema=database() and table_name='kg_stay_order' and column_name='agreement_snapshot') then
        set @kg_s='select count(*) into @kg_v92_orders from kg_stay_order where agreement_snapshot is not null';
        prepare kg_st from @kg_s; execute kg_st; deallocate prepare kg_st;
        if @kg_v92_orders>0 then
            signal sqlstate '45000' set message_text='V92 rollback blocked: notice snapshots exist';
        end if;
    end if;
    if exists (select 1 from information_schema.columns where table_schema=database() and table_name='kg_stay' and column_name='booking_notice_config') then
        set @kg_s='select count(*) into @kg_v92_stays from kg_stay where booking_notice_config is not null';
        prepare kg_st from @kg_s; execute kg_st; deallocate prepare kg_st;
        if @kg_v92_stays>0 then
            signal sqlstate '45000' set message_text='V92 rollback blocked: custom notices exist';
        end if;
    end if;
    call kg_drop_col_if_present('kg_stay_order','agreement_snapshot');
    call kg_drop_col_if_present('kg_stay','booking_notice_config');
    if exists (select 1 from information_schema.columns where table_schema=database() and table_name='kg_stay_order' and column_name='agreement_version' and data_type='varchar' and character_maximum_length=80) then
        alter table kg_stay_order modify column agreement_version varchar(16) null comment '同意的预订须知版本';
    end if;
    delete from kg_schema_version where version=92;
end$$
delimiter ;
call kg_rollback_stay_booking_notice();
drop procedure kg_rollback_stay_booking_notice;

