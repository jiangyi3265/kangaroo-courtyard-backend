create procedure kg_rollback_inbox_interactions()
begin
    if coalesce(@kg_allow_inbox_rollback, 0) <> 1 then
        signal sqlstate '45000' set message_text = 'V43 rollback requires stopped application and explicit authorization';
    end if;
    if exists (select 1 from kg_schema_version where version > 43) then
        signal sqlstate '45000' set message_text = 'V43 rollback blocked by later migrations';
    end if;
    -- 评论 / 点赞通知（含 V43 改归的老评论通知、新版本写的评论和点赞通知）改回系统通知
    update kg_message set category = 'system' where mode = 'user' and category in ('comment', 'like');
    delete from sys_dict_data where dict_type = 'kg_msg_category' and dict_value in ('comment', 'like');
    call kg_drop_col_if_present('kg_message', 'actor_id');
    delete from kg_schema_version where version = 43;
end$$
